// The composition root supplies modules; origin does not grant extra services.
const module = (
  id,
  name,
  description,
  surfaces,
  entry,
  requires,
  navigation,
  required = false,
) => ({
  id,
  builtin: true,
  required,
  enabled: true,
  manifest: {
    apiVersion: 1,
    id,
    name,
    description,
    surfaces,
    entry: new URL(entry, import.meta.url).href,
    requires,
    ...(navigation ? { navigation } : {}),
  },
});
