// The composition root supplies modules; origin does not grant extra services.
const module = (
  id,
  name,
  description,
  surfaces,
  entry,
  requires,
  icon,
  required = false,
  settingsGroup = "builtin",
  layout = "form",
) => ({
  id,
  source: "builtin",
  settingsGroup,
  chromeIcon: icon,
  required,
  enabled: true,
  manifest: {
    apiVersion: 4,
    id,
    name,
    description,
    views: [{ surfaces, entry: new URL(entry, import.meta.url).href, requires, layout, isolation: "light" }],
  },
});
